"""The daily-cutoff batch: materialize active subscriptions into delivery_orders.

Idempotent + chunked: subscriptions are processed in batches with a commit per
chunk, so a huge run never holds one giant transaction. A *session-level* advisory
lock (held across commits, unlike an xact lock) serializes runs for a date; a
second concurrent run (cron + manual admin) sees the lock held and skips.

Per order we take a row lock and refuse to clobber anything already past
'generated'/'frozen' (i.e. assigned/dispatched/delivered). A rerun also REMOVES a
still-'generated' order whose subscription no longer wants that day (skipped, all
items off, paused or cancelled since the earlier run), so it isn't delivered + billed.

A run with per-subscription failures ends 'partial' (not 'frozen') and reports the
failure count so the scheduler retries; any interruption (incl. cancellation on a job
timeout) marks the run 'failed' instead of leaving it 'generating' forever.
"""
import datetime as dt
import logging
import secrets
from dataclasses import dataclass, field

from sqlalchemy import BigInteger, any_, bindparam, delete, exists, func, select
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.redis import redis_client
from app.models.billing import Wallet
from app.models.delivery import DeliveryOrder, DeliveryOrderItem, ScheduleRun
from app.models.shop import CustomerAccount, DeliveryAssignment, Shop
from app.models.subscription import Subscription, SubscriptionItem, SubscriptionOverride
from app.models.user import User
from app.services import notifications as notify
from app.services.pricing import PriceBook, load_price_book
from app.services.subscription import plan_from, today_ist

CHUNK = 200
# Redis lock TTL. A real cutoff finishes in well under this; the key auto-expires so a
# crashed run can never deadlock a date forever (a pg session-advisory lock could not be
# held reliably across the per-chunk commits / connection-pool churn).
_LOCK_TTL = 3600

log = logging.getLogger("drs.cutoff")


@dataclass
class _Ctx:
    """Reference data preloaded once per run so per-subscription work does no
    shop/account/user/price lookups (eliminates the cutoff's N+1)."""

    shops: dict[int, Shop]
    accounts: dict[int, CustomerAccount]
    owners: dict[int, User | None]  # keyed by account_id
    wallets: dict[int, float]  # account_id -> AVAILABLE balance (minus open reservations)
    book: PriceBook
    removed: int = 0  # stale generated orders dropped this run
    # account_id -> the ACTUAL wallet balance (what the customer sees), for messages.
    balances: dict[int, float] = field(default_factory=dict)


def _any(col, ids):
    """`col = ANY(:array)` — ONE bind parameter however many ids (an expanding IN emits
    one per id, and asyncpg refuses more than 32,767 at this scale)."""
    return col == any_(bindparam(None, list(ids), type_=ARRAY(BigInteger)))


async def _load_ctx(db: AsyncSession, delivery_date: dt.date, sub_ids: list[int]) -> _Ctx:
    # Built from the SAME subscription ids the run iterates (taken first), so a sub
    # activated between the two queries can't end up with no shop/tier in the context.
    rows = (
        await db.execute(
            select(Subscription.shop_id, Subscription.account_id).where(
                _any(Subscription.id, sub_ids)
            )
        )
    ).all() if sub_ids else []
    shop_ids = {r[0] for r in rows}
    account_ids = {r[1] for r in rows}
    shops = (
        {s.id: s for s in (await db.execute(select(Shop).where(_any(Shop.id, shop_ids)))).scalars()}
        if shop_ids
        else {}
    )
    accounts = (
        {
            a.id: a
            for a in (
                await db.execute(
                    select(CustomerAccount).where(_any(CustomerAccount.id, account_ids))
                )
            ).scalars()
        }
        if account_ids
        else {}
    )
    owner_ids = {a.owner_user_id for a in accounts.values()}
    users = (
        {u.id: u for u in (await db.execute(select(User).where(_any(User.id, owner_ids)))).scalars()}
        if owner_ids
        else {}
    )
    owners = {a.id: users.get(a.owner_user_id) for a in accounts.values()}
    # Preload wallet balances for ALL prepaid accounts (retail and B2B) so the funds
    # gate below does no per-subscription lookup (keeps the cutoff N+1-free).
    prepaid_ids = {a.id for a in accounts.values() if a.billing_mode == "prepaid_wallet"}
    wallets: dict[int, float] = {}
    balances: dict[int, float] = {}
    if prepaid_ids:
        wrows = (
            await db.execute(
                select(Wallet.account_id, Wallet.balance).where(_any(Wallet.account_id, prepaid_ids))
            )
        ).all()
        wallets = {aid: float(bal) for aid, bal in wrows}
        balances = dict(wallets)
        # The funds gate must also reserve OTHER open, not-yet-billed orders of the
        # account (e.g. a later date generated by an admin run): each passing on its own
        # would together overdraw the wallet.
        open_rows = (
            await db.execute(
                select(DeliveryOrder.account_id, func.coalesce(func.sum(DeliveryOrder.total), 0))
                .where(
                    _any(DeliveryOrder.account_id, prepaid_ids),
                    DeliveryOrder.delivery_date != delivery_date,
                    DeliveryOrder.delivery_date >= today_ist(),
                    DeliveryOrder.status.in_(("generated", "frozen")),
                )
                .group_by(DeliveryOrder.account_id)
            )
        ).all()
        for aid, reserved in open_rows:
            wallets[aid] = round(wallets.get(aid, 0.0) - float(reserved), 2)
    # Price AS OF the delivery date (not "now") so a price scheduled to take effect on the
    # delivery day is applied and an expiring price isn't used past its date.
    return _Ctx(
        shops, accounts, owners, wallets, await load_price_book(db, today=delivery_date),
        balances=balances,
    )


def _deliverable_sub():
    """An active subscription whose shop is active and whose account owner is active:
    a deactivated shop or a suspended/erased user must stop generating (and billing)
    deliveries even though the subscription row itself is still 'active'."""
    return (
        (Subscription.status == "active")
        & exists().where(Shop.id == Subscription.shop_id, Shop.status == "active")
        & exists().where(
            CustomerAccount.id == Subscription.account_id,
            User.id == CustomerAccount.owner_user_id,
            User.status == "active",
        )
    )


async def _drop_if_stale(db: AsyncSession, order: DeliveryOrder | None) -> bool:
    """Delete a still-'generated'/'frozen' SUBSCRIPTION order that should no longer exist
    (the plan for that day became empty). Never touches dispatched/delivered or one-time
    orders. Returns True when an order was removed."""
    if order is None or order.origin != "subscription" or order.status not in ("generated", "frozen"):
        return False
    await db.execute(delete(DeliveryOrderItem).where(DeliveryOrderItem.delivery_order_id == order.id))
    await db.delete(order)
    return True


async def _materialize_one(
    db: AsyncSession, sub: Subscription, delivery_date: dt.date, run_id: int, ctx: _Ctx,
    lines: list[dict], order: DeliveryOrder | None,
) -> bool:
    """`lines` is the preloaded plan; `order` the (already row-locked) existing order
    for (shop, date), if any."""
    if not lines:
        if await _drop_if_stale(db, order):  # skipped / all items off since an earlier run
            ctx.removed += 1
        return False

    shop = ctx.shops.get(sub.shop_id)
    account = ctx.accounts.get(sub.account_id)
    tier_id = ctx.book.tier_for(shop, account) if shop is not None else None

    # Price the plan first (so the prepaid funds gate can run before we touch the order).
    priced: list[tuple[int, float, float, float]] = []  # (product_id, qty, unit_price, line_total)
    subtotal = 0.0
    for line in lines:
        unit_price = ctx.book.unit_price(line["product_id"], tier_id, line["qty"])
        if unit_price is None:
            # Misconfiguration: a subscribed product has no price for this tier. Skip the
            # line (never materialize a silent ₹0 charge) and log loudly for ops.
            log.warning(
                "cutoff: no price for product %s (tier %s) on sub %s — line skipped",
                line["product_id"], tier_id, sub.id,
            )
            continue
        line_total = round(unit_price * line["qty"], 2)
        subtotal += line_total
        priced.append((line["product_id"], line["qty"], unit_price, line_total))
    if not priced:
        if await _drop_if_stale(db, order):  # nothing priced -> nothing to deliver
            ctx.removed += 1
        return False
    subtotal = round(subtotal, 2)  # re-round the float accumulation before the funds gate

    if order is not None and (
        order.status not in ("generated", "frozen") or order.origin != "subscription"
    ):
        # Never clobber an assigned/dispatched/delivered order, nor a non-subscription
        # (one-time/manual) order that happens to share this (shop, date).
        return False

    # Prepaid funds gate (retail AND B2B): never schedule a prepaid account into the
    # negative. If the wallet can't cover tomorrow's order, skip it, drop any stale
    # pending order from a prior run, and nudge the customer to top up. (Billing re-checks
    # under the wallet lock at delivery time; this is the early, planning-time gate.)
    if (
        account is not None
        and account.billing_mode == "prepaid_wallet"
        and ctx.wallets.get(sub.account_id, 0.0) < subtotal
    ):
        if order is not None:
            await db.execute(
                delete(DeliveryOrderItem).where(DeliveryOrderItem.delivery_order_id == order.id)
            )
            await db.delete(order)
        owner = ctx.owners.get(sub.account_id)
        if owner is not None:
            # Show the customer their REAL balance (what their wallet says), not the
            # planning figure net of other open orders; the gap is reported separately.
            balance = round(ctx.balances.get(sub.account_id, 0.0), 2)
            available = round(ctx.wallets.get(sub.account_id, 0.0), 2)
            await notify.emit_event(
                db, "wallet.low", owner,
                {"balance": balance, "needed": subtotal,
                 "reserved": round(max(balance - available, 0.0), 2),
                 "subscription_id": sub.id, "date": str(delivery_date)},
                account_id=sub.account_id,
                dedupe_key=f"cutoff.skipped_lowbalance:{sub.id}:{delivery_date}",
            )
        log.info(
            "cutoff: sub %s skipped — prepaid wallet %.2f < order %.2f",
            sub.id, ctx.wallets.get(sub.account_id, 0.0), subtotal,
        )
        return False

    if order is None:
        order = DeliveryOrder(
            delivery_date=delivery_date,
            account_id=sub.account_id,
            shop_id=sub.shop_id,
            origin="subscription",
            schedule_run_id=run_id,
            status="generated",
        )
        db.add(order)
        await db.flush()
    else:
        order.schedule_run_id = run_id
        order.status = "generated"
        await db.execute(
            delete(DeliveryOrderItem).where(DeliveryOrderItem.delivery_order_id == order.id)
        )

    for product_id, qty, unit_price, line_total in priced:
        db.add(
            DeliveryOrderItem(
                delivery_order_id=order.id,
                product_id=product_id,
                qty_planned=qty,
                unit_price=unit_price,
                line_total=line_total,
                status="planned",
            )
        )
    order.subtotal = subtotal
    order.total = subtotal
    order.amount_due = subtotal
    # Decrement the preloaded wallet snapshot so a SECOND subscription of the same prepaid
    # account this run is gated against the remaining (not the original) balance.
    if sub.account_id in ctx.wallets:
        ctx.wallets[sub.account_id] = round(ctx.wallets[sub.account_id] - subtotal, 2)

    # Tell the account owner tomorrow's order is set (idempotent per delivery_order;
    # a cutoff re-run hits the dedupe savepoint and skips silently).
    owner = ctx.owners.get(sub.account_id)
    if owner is not None:
        await notify.emit_event(
            db,
            "order.generated",
            owner,
            {"date": str(delivery_date), "summary": f"{len(priced)} item(s)", "total": subtotal,
             "delivery_id": order.id},
            account_id=sub.account_id,
            dedupe_key=f"order.generated:{order.id}",
        )
    return True


async def _notify_rider_routes(db: AsyncSession, delivery_date: dt.date) -> None:
    """Tell each rider their route for the date is ready (route.assigned, push). Deduped
    on (rider, date, stop count): re-running the cutoff re-notifies a rider only when
    their number of stops actually changed. Best-effort: never fails the run."""
    try:
        rows = (
            await db.execute(
                select(DeliveryAssignment.delivery_id, func.count(DeliveryOrder.id))
                .join(DeliveryOrder, DeliveryOrder.shop_id == DeliveryAssignment.shop_id)
                .where(
                    DeliveryAssignment.active.is_(True),
                    DeliveryOrder.delivery_date == delivery_date,
                    DeliveryOrder.status.in_(("generated", "frozen")),
                )
                .group_by(DeliveryAssignment.delivery_id)
            )
        ).all()
        if not rows:
            return
        riders = {
            u.id: u for u in (
                await db.execute(select(User).where(_any(User.id, [r[0] for r in rows])))
            ).scalars()
            if u.status == "active"
        }
        for rider_id, stops in rows:
            rider = riders.get(rider_id)
            if rider is None:
                continue
            await notify.emit_event(
                db, "route.assigned", rider, {"date": str(delivery_date), "stops": int(stops)},
                dedupe_key=f"route.assigned:{rider_id}:{delivery_date}:{int(stops)}",
            )
        await db.commit()
    except Exception:
        await db.rollback()
        log.exception("cutoff: rider route notifications failed for %s", delivery_date)


async def run_cutoff(db: AsyncSession, delivery_date: dt.date) -> dict:
    # Redis lock keyed by the delivery date. Unlike a pg advisory lock, it survives the
    # per-chunk commits and connection-pool churn below. Fail-open if Redis is down — the
    # cutoff is critical and UNIQUE(shop_id, delivery_date) + row locks already prevent
    # data corruption from a concurrent run; the lock only avoids duplicated work.
    lock_key = f"cutoff:lock:{delivery_date.isoformat()}"
    token = secrets.token_hex(8)
    lock_acquired: bool | None = None
    try:
        lock_acquired = bool(await redis_client.set(lock_key, token, nx=True, ex=_LOCK_TTL))
    except Exception:
        log.warning("cutoff: redis lock unavailable for %s, proceeding without it", delivery_date)
        lock_acquired = None
    if lock_acquired is False:
        return {
            "schedule_run_id": None,
            "delivery_date": delivery_date,
            "orders_generated": 0,
            "skipped": "locked",
        }
    run_id = None
    try:
        run = ScheduleRun(for_delivery_date=delivery_date, status="generating")
        db.add(run)
        await db.flush()
        run_id = run.id
        await db.commit()  # persist the run row up front

        ids = (
            await db.execute(
                select(Subscription.id)
                .where(_deliverable_sub())
                .order_by(Subscription.id)
            )
        ).scalars().all()
        ctx = await _load_ctx(db, delivery_date, list(ids))  # reference data once (no N+1)

        count = 0
        failed = 0
        for start in range(0, len(ids), CHUNK):
            chunk_ids = ids[start : start + CHUNK]
            subs = (
                await db.execute(
                    select(Subscription)
                    .where(Subscription.id.in_(chunk_ids))
                    .order_by(Subscription.id)
                )
            ).scalars().all()
            # Batch-preload the chunk's active items, that date's overrides, and the
            # existing orders (row-locked in id order) — 3 queries per chunk instead of
            # ~3 per subscription.
            items_by_sub: dict[int, list[SubscriptionItem]] = {}
            for it in (
                await db.execute(
                    select(SubscriptionItem).where(
                        SubscriptionItem.subscription_id.in_(chunk_ids),
                        SubscriptionItem.active.is_(True),
                    )
                )
            ).scalars():
                items_by_sub.setdefault(it.subscription_id, []).append(it)
            item_ids = [i.id for lst in items_by_sub.values() for i in lst]
            overrides = (
                {
                    o.subscription_item_id: o
                    for o in (
                        await db.execute(
                            select(SubscriptionOverride).where(
                                SubscriptionOverride.subscription_item_id.in_(item_ids),
                                SubscriptionOverride.for_date == delivery_date,
                            )
                        )
                    ).scalars()
                }
                if item_ids
                else {}
            )
            shop_ids = [s_.shop_id for s_ in subs]
            orders = {
                o.shop_id: o
                for o in (
                    await db.execute(
                        select(DeliveryOrder)
                        .where(
                            DeliveryOrder.shop_id.in_(shop_ids),
                            DeliveryOrder.delivery_date == delivery_date,
                        )
                        .order_by(DeliveryOrder.id)
                        .with_for_update()
                    )
                ).scalars()
            }
            for sub in subs:
                lines = plan_from(sub, items_by_sub.get(sub.id, []), overrides, delivery_date)
                # Isolate each subscription in a savepoint: one bad sub (data/price
                # error) is logged and counted instead of aborting the whole run.
                # The run's tallies and the wallet snapshot are only kept if the savepoint
                # actually commits: a failure (even while releasing it) rolls the DB work
                # back, so its counts/reservation must be rolled back too.
                removed_before = ctx.removed
                wallet_before = ctx.wallets.get(sub.account_id)
                try:
                    async with db.begin_nested():
                        generated = await _materialize_one(
                            db, sub, delivery_date, run_id, ctx, lines, orders.get(sub.shop_id)
                        )
                except Exception:
                    ctx.removed = removed_before
                    if wallet_before is not None:
                        ctx.wallets[sub.account_id] = wallet_before
                    failed += 1
                    log.exception("cutoff: subscription %s failed — skipped", sub.id)
                else:
                    if generated:
                        count += 1
            await db.commit()  # commit per chunk

        # Orders from an earlier run whose subscription is no longer active (paused /
        # cancelled since) must not be delivered and billed.
        removed = ctx.removed
        stale = (
            await db.execute(
                select(DeliveryOrder)
                .where(
                    DeliveryOrder.delivery_date == delivery_date,
                    DeliveryOrder.origin == "subscription",
                    DeliveryOrder.status.in_(("generated", "frozen")),
                    # Decided NOW (not from the run's starting snapshot): a sub resumed
                    # mid-run keeps its valid earlier order. Also no N-param NOT IN.
                    ~exists().where(
                        Subscription.shop_id == DeliveryOrder.shop_id, _deliverable_sub()
                    ),
                )
                .order_by(DeliveryOrder.id)
                .with_for_update()
            )
        ).scalars().all()
        for order in stale:
            if await _drop_if_stale(db, order):
                removed += 1
        await db.commit()
        await _notify_rider_routes(db, delivery_date)

        run = await db.get(ScheduleRun, run_id)
        run.status = "partial" if failed else "frozen"
        run.orders_generated = count
        run.finished_at = dt.datetime.now(dt.UTC)
        await db.commit()
        return {
            "schedule_run_id": run_id,
            "delivery_date": delivery_date,
            "orders_generated": count,
            "orders_removed": removed,
            "failed": failed,
        }
    except BaseException:
        # Never leave the run stuck 'generating' — including asyncio cancellation when the
        # worker's job timeout fires (CancelledError is not an Exception). Mark it failed.
        await db.rollback()
        if run_id is not None:
            try:
                run = await db.get(ScheduleRun, run_id)
                if run is not None:
                    run.status = "failed"
                    run.finished_at = dt.datetime.now(dt.UTC)
                    await db.commit()
            except Exception:
                await db.rollback()
        raise
    finally:
        # Clear any aborted-transaction state before touching the DB again.
        try:
            await db.rollback()
        except Exception:
            pass
        # Release the Redis lock only if we still own it (compare token so we never
        # delete a lock a later run acquired after ours expired).
        if lock_acquired:
            try:
                if await redis_client.get(lock_key) == token:
                    await redis_client.delete(lock_key)
            except Exception:
                pass
